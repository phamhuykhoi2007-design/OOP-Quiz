const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const context = vm.createContext({});
const mcq = i => ({ type: 'mcq', id: 'm' + i, ch: i % 5 + 1, title: 'Câu ' + i,
  options: ['class', 'Class', 'struct', 'interface'], answer: i % 4, explain: 'Giải thích', source: 'slide' });
const essay = i => ({ type: 'essay', id: 'e' + i, ch: 3, title: 'Bài ' + i,
  requirements: ['Viết lớp'], lines: [['class A { ', { b: 0 }, ' }']],
  blanks: [{ ok: ['public string Ten { get; set; }'], explain: 'Property' }], explain: 'Giải thích', source: 'ảnh' });
context.ExamMCQ = { generate: () => Array.from({ length: 40 }, (_, i) => mcq(i)) };
context.ExamEssay = { generate: () => Array.from({ length: 5 }, (_, i) => essay(i)) };
vm.runInContext(fs.readFileSync(path.join(__dirname, '../exam-core.js'), 'utf8'), context);
const core = context.ExamCore;
const deck = core.build(() => 0.5);
assert.equal(deck.length, 45);
assert.equal(core.validate(deck), true);
assert.equal(core.validate(deck.slice(1)), false);
const duplicate = structuredClone(deck); duplicate[1].id = duplicate[0].id;
assert.equal(core.validate(duplicate), false);
const badOptions = structuredClone(deck); badOptions[0].options[1] = 'class';
assert.equal(core.validate(badOptions), false);
const badBlank = structuredClone(deck); badBlank[40].lines[0][1].b = 9;
assert.equal(core.validate(badBlank), false);
assert.equal(core.check(mcq(1), 1).correct, true);
assert.equal(core.check(mcq(1), '1').correct, false);
assert.equal(core.check(mcq(1), null).correct, false);
assert.equal(core.check(essay(0), [' public string Ten{get;set;} ']).correct, true);
assert.equal(core.check(essay(0), ['public string ten { get; set; }']).correct, false);
assert.equal(core.check(essay(0), ['publicstring Ten { get; set; }']).correct, false);
const literal = essay(0); literal.blanks[0].ok = ['"a b"'];
assert.equal(core.check(literal, ['"ab"']).correct, false);
assert.equal(core.check(literal, ['"a b"']).correct, true);
const expression = essay(0);
expression.blanks[0].ok = ['a <= b && a != c', 'a < b || a == b'];
assert.equal(core.check(expression, ['a<=b&&a!=c']).correct, true);
assert.equal(core.check(expression, ['a<b || a==b']).correct, true);
assert.equal(core.check(expression, ['a < = b && a != c']).correct, false);
expression.blanks[0].ok = ['@"a ""b"""'];
assert.equal(core.check(expression, [' @"a ""b""" ']).correct, true);
assert.equal(core.check(expression, ['@"ab"']).correct, false);
const s = core.summary(deck, { m0: { status: 'ok' }, e0: { status: 'revealed' }, m1: { attempts: 2 } });
assert.equal(s.mcq.correct, 1); assert.equal(s.mcq.total, 40);
assert.equal(s.essay.revealed, 1); assert.equal(s.essay.correct, 0);
assert.equal(s.completed, 2);
assert.equal(core.restore('bad json'), null);
assert.equal(core.restore(JSON.stringify({ version: 2, deck })), null);
const restored = core.restore(JSON.stringify({ version: 3, deck, answers: { m0: { value: 0, attempts: 1, status: 'ok' } }, idx: 41, finished: false }));
assert.equal(restored.idx, 41); assert.equal(restored.answers.m0.value, 0);
const missingChoice = core.restore(JSON.stringify({ version: 3, deck, answers: { m0: { attempts: 0 } } }));
assert.equal(missingChoice.answers.m0.value, null);
assert.equal(core.restore(JSON.stringify({ version: 3, deck, answers: { m0: { value: 1, status: 'ok' } } })), null);
assert.equal(core.restore(JSON.stringify({ version: 3, deck, answers: { e0: { value: ['wrong'], status: 'revealed' } } })), null);
assert.equal(core.restore(JSON.stringify({ version: 3, deck: [], answers: {} })), null);
assert.equal(core.restore(JSON.stringify({ version: 3, deck, answers: { e0: { value: 'invalid' } } })), null);
assert.equal(core.restore(JSON.stringify({ version: 3, deck, answers: { m0: { value: 7 } } })), null);
assert.equal(core.restore(JSON.stringify({ version: 3, deck, answers: {}, idx: 100 })).idx, 0);
const beforeRefresh = { version: 3, deck, answers: { m0: { value: 0, attempts: 1, status: 'ok' }, e0: { value: ['draft'], attempts: 0 } }, idx: 44, finished: true };
const refreshed = core.refreshEssays(beforeRefresh, () => 0.25);
assert.equal(refreshed.deck.length, 45);
assert.equal(refreshed.deck[0], beforeRefresh.deck[0]);
assert.equal(refreshed.answers.m0.status, 'ok');
assert.equal(Object.hasOwn(refreshed.answers, 'e0'), false);
assert.equal(beforeRefresh.answers.e0.value[0], 'draft');
assert.equal(refreshed.idx, 40); assert.equal(refreshed.finished, false);
const wrongForm = structuredClone(deck);
wrongForm[40].formVersion = 2; wrongForm[40].formId = 'unknown';
wrongForm[40].introduction = 'Intro'; wrongForm[40].sections = null;
assert.equal(core.validate(wrongForm), false);
console.log('exam-core: counts, schema, grading, literal/case sensitivity, summary and restore passed');
